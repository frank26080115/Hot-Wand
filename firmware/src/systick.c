// -----------------------------------------------------------------------------
// Includes
// -----------------------------------------------------------------------------

#include "systick.h"

#include "stm32f0xx_hal.h"

// -----------------------------------------------------------------------------
// Main Flow
// -----------------------------------------------------------------------------

void systick_init(void)
{
    HAL_InitTick(TICK_INT_PRIORITY);
}

void SysTick_Handler_Impl(void)
{
    HAL_IncTick();
}

// -----------------------------------------------------------------------------
// Getters and Setters
// -----------------------------------------------------------------------------

uint32_t systick_get_ms(void)
{
    return HAL_GetTick();
}
